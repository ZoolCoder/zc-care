package main

import (
	"fmt"
	"io"
	"slices"
	"strings"
	"text/tabwriter"

	"github.com/zoolcoder/zc-care/internal/engine"
)

// writeItems prints the inventory as one table, or as JSON.
func writeItems(w io.Writer, rows []engine.TargetItems, asJSON bool) error {
	if asJSON {
		return writeJSON(w, rows)
	}
	tw := tabwriter.NewWriter(w, 0, 0, 2, ' ', 0)
	fmt.Fprintln(tw, "TARGET\tKIND\tNAME\tSTATE\tVERSION\tAPP\tABOUT")
	for _, r := range rows {
		if r.Error != "" {
			fmt.Fprintf(tw, "%s\t\t\terror\t\t\t%s\n", r.Target, r.Error)
		}
		for _, i := range r.Items {
			fmt.Fprintf(tw, "%s\t%s\t%s\t%s\t%s\t%s\t%s\n",
				r.Target, i.Kind, i.Name, i.State, versions(i), dash(i.App), about(i))
		}
	}
	return tw.Flush()
}

func dash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

// filterItems keeps the items whose state and kind are in the comma lists;
// an empty list keeps every value.
func filterItems(rows []engine.TargetItems, states, kinds string) []engine.TargetItems {
	if states == "" && kinds == "" {
		return rows
	}
	keep := func(list, v string) bool {
		return list == "" || slices.Contains(strings.Split(list, ","), v)
	}
	for n, r := range rows {
		var items []engine.Item
		for _, i := range r.Items {
			if keep(states, i.State) && keep(kinds, i.Kind) {
				items = append(items, i)
			}
		}
		rows[n].Items = items
	}
	return rows
}

// versions is the installed version, and the newer one when there is one.
func versions(i engine.Item) string {
	if i.Latest != "" {
		return dash(i.Version) + " -> " + i.Latest
	}
	return dash(i.Version)
}

// about is why the manifest says an item is there, else what its package
// manager says it is.
func about(i engine.Item) string {
	if i.Why != "" {
		return i.Why
	}
	return i.Desc
}

// writeAdoc prints the declared packages and runtimes as an AsciiDoc page:
// one table per manifest section, each item linked to its homepage, with why
// it is there. Versions are left out so the page changes only when the
// manifests do; so are dotfiles and other targets.
func writeAdoc(w io.Writer, rows []engine.TargetItems) error {
	var b strings.Builder
	b.WriteString("= Software\n\nGenerated by `" + name + " list -adoc` from the manifests. " +
		"To change a line, edit the comment at the end of the entry in its manifest, then generate this page again.\n")
	for _, r := range rows {
		if r.Provider != "packages" && r.Provider != "tools" {
			continue
		}
		var order []string
		bySection := map[string][]engine.Item{}
		seen := map[string]bool{}
		for _, i := range r.Items {
			// A runtime with several versions is one row.
			if i.State == engine.Extra || i.Kind == "tap" || seen[i.Kind+":"+i.Name] {
				continue
			}
			seen[i.Kind+":"+i.Name] = true
			s := i.Section
			if s == "" {
				s = r.Target
			}
			if _, ok := bySection[s]; !ok {
				order = append(order, s)
			}
			bySection[s] = append(bySection[s], i)
		}
		for _, s := range order {
			fmt.Fprintf(&b, "\n== %s\n\n[%%header,cols=\"1,3\"]\n|===\n|Name |Why\n\n", s)
			for _, i := range bySection[s] {
				label := i.Name
				if i.App != "" {
					label = i.App
				}
				if strings.HasPrefix(i.Homepage, "https://") {
					label = i.Homepage + "[" + label + "]"
				}
				fmt.Fprintf(&b, "|%s |%s\n", cell(label), cell(about(i)))
			}
			b.WriteString("|===\n")
		}
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func cell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
